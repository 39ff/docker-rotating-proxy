# minimal YAML emitter (block style, double-quoted strings when needed)

_PLAIN_RE = re.compile(r"[A-Za-z_/][A-Za-z0-9_./-]*\Z")
_KEY_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_.-]*\Z")
_RESERVED = {"y", "n", "yes", "no", "true", "false", "on", "off", "null", "~"}


def _scalar(value):
    if value is True:
        return "true"
    if value is False:
        return "false"
    if value is None:
        return "null"
    if isinstance(value, int):
        return str(value)
    text = str(value)
    if _PLAIN_RE.match(text) and text.lower() not in _RESERVED:
        return text
    return json.dumps(text, ensure_ascii=True)


def _inline(value):
    if isinstance(value, dict):
        return "{}"
    if isinstance(value, list):
        return "[]"
    return _scalar(value)


def _key(key):
    key = str(key)
    if _KEY_RE.match(key) and key.lower() not in _RESERVED:
        return key
    return json.dumps(key, ensure_ascii=True)


def _emit(value, indent, out):
    pad = " " * indent
    if isinstance(value, dict):
        for key, item in value.items():
            if isinstance(item, (dict, list)) and item:
                out.append("{}{}:".format(pad, _key(key)))
                _emit(item, indent + 2, out)
            else:
                out.append("{}{}: {}".format(pad, _key(key), _inline(item)))
    else:
        for item in value:
            if isinstance(item, (dict, list)) and item:
                sub = []
                _emit(item, indent + 2, sub)
                sub[0] = pad + "- " + sub[0][indent + 2:]
                out.extend(sub)
            else:
                out.append("{}- {}".format(pad, _inline(item)))


def to_yaml(value):
    out = []
    _emit(value, 0, out)
    return "\n".join(out) + "\n"


