# proxyList.txt


class Upstream:
    """One line of proxyList.txt / publicProxyList.txt."""

    __slots__ = ("host", "port", "scheme", "username", "password", "public_list")

    def __init__(self, host, port, scheme="", username="", password="",
                 public_list=False):
        self.host = host
        self.port = port
        self.scheme = scheme
        self.username = username
        self.password = password
        self.public_list = public_list

    @property
    def addr(self):
        if ":" in self.host:
            return "[{}]:{}".format(self.host, self.port)
        return "{}:{}".format(self.host, self.port)

    @property
    def has_static_port(self):
        return self.scheme in STATIC_SCHEMES and not self.public_list

    def key(self):
        return (self.host.lower(), self.port, self.scheme, self.username,
                self.password)

    def describe(self):
        return "{} {}".format(self.scheme or "public-http", self.addr)


def _check_host(host):
    if not host:
        raise ValueError("missing host")
    if _BAD_CRED_RE.search(host):
        raise ValueError("host contains whitespace, quotes or control characters")
    if re.fullmatch(r"[0-9.]+", host):
        try:
            ipaddress.IPv4Address(host)
        except ValueError:
            raise ValueError("invalid IPv4 address {!r}".format(host))
        return host
    if not _HOSTNAME_RE.match(host):
        raise ValueError("invalid hostname {!r}".format(host))
    return host


def _check_port(text):
    if not re.fullmatch(r"[0-9]{1,5}", text):
        raise ValueError("invalid port {!r}".format(text))
    port = int(text)
    if not 1 <= port <= 65535:
        raise ValueError("port {} out of range 1-65535".format(port))
    return port


def _check_credential(value, what):
    if _BAD_CRED_RE.search(value):
        raise ValueError(
            "{} contains whitespace, quotes, backslashes or control "
            "characters".format(what))
    return value


def parse_proxy_line(line, public_list=False):
    """Parse one proxyList line.

    Returns an Upstream, None for blank/comment lines, raises ValueError
    with a human readable reason for invalid lines.

    Format: host:port[:scheme[:user:pass]]; IPv6 hosts as [addr]:port...
    The password may contain ':' (everything after the 4th separator).
    """
    line = line.strip()
    if not line or line.startswith("#"):
        return None

    if line.startswith("["):
        end = line.find("]")
        if end < 0:
            raise ValueError("unterminated '[' in IPv6 address")
        host = line[1:end]
        rest = line[end + 1:]
        if not rest.startswith(":"):
            raise ValueError("expected ':port' after IPv6 address")
        if "%" in host:
            raise ValueError("IPv6 zone IDs are not supported")
        try:
            ip = ipaddress.IPv6Address(host)
        except ValueError:
            raise ValueError("invalid IPv6 address {!r}".format(host))
        host = str(ip)
        fields = rest[1:].split(":", 3)
    else:
        fields = line.split(":", 4)
        host = fields.pop(0)

    fields += [""] * (4 - len(fields))
    port_text, scheme, username, password = fields
    try:
        if not line.startswith("["):
            host = _check_host(host)
        if not port_text:
            raise ValueError("missing port")
        port = _check_port(port_text)
    except ValueError:
        if _looks_like_bare_ipv6(line):
            raise ValueError(
                "IPv6 addresses must be written in brackets, e.g. [::1]:1080")
        raise
    scheme = scheme.lower()
    if scheme not in SCHEMES:
        raise ValueError("unknown scheme {!r} (expected one of: {})".format(
            scheme, ", ".join(s for s in SCHEMES if s)))
    if bool(username) != bool(password):
        raise ValueError("username and password must both be set or both be empty")
    if username:
        if not scheme:
            raise ValueError(
                "credentials need a scheme (use httpsquid for an "
                "authenticated HTTP proxy)")
        _check_credential(username, "username")
        _check_credential(password, "password")
    return Upstream(host, port, scheme, username, password, public_list)


def _looks_like_bare_ipv6(line):
    parts = line.split(":")
    for end in range(min(len(parts), 9), 2, -1):
        try:
            ipaddress.IPv6Address(":".join(parts[:end]))
        except ValueError:
            continue
        return True
    return False


def read_proxy_list(path, public_list, warn):
    """Read a proxy list file; invalid lines are reported and skipped."""
    if not path.is_file():
        return []
    upstreams = []
    problems = 0
    text = path.read_text(encoding="utf-8", errors="replace")
    for lineno, line in enumerate(text.splitlines(), 1):
        try:
            upstream = parse_proxy_line(line, public_list)
        except ValueError as exc:
            problems += 1
            if problems <= MAX_WARNINGS_PER_FILE:
                warn("{}:{}: skipped: {}".format(path.name, lineno, exc))
            continue
        if upstream is not None:
            upstreams.append(upstream)
    if problems > MAX_WARNINGS_PER_FILE:
        warn("{}: {} more invalid lines skipped".format(
            path.name, problems - MAX_WARNINGS_PER_FILE))
    return upstreams


def dedupe(upstreams, warn):
    """Drop repeated upstreams (first occurrence wins)."""
    seen = set()
    result = []
    duplicates = 0
    for upstream in upstreams:
        key = upstream.key()
        if key in seen:
            duplicates += 1
            if duplicates <= MAX_WARNINGS_PER_FILE:
                warn("duplicate upstream {} ignored".format(upstream.describe()))
            continue
        seen.add(key)
        result.append(upstream)
    if duplicates > MAX_WARNINGS_PER_FILE:
        warn("{} more duplicate upstreams ignored".format(
            duplicates - MAX_WARNINGS_PER_FILE))
    return result


