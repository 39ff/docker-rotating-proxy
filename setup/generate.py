def write_file(path, content, mode=0o644):
    """Atomically replace `path`; returns True when the content changed.

    Atomic replacement matters: gost re-reads the hot-reloaded files every
    30 s and must never see a half-written file.  config/ is bind-mounted as
    a directory, so the renamed file is visible inside the container.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        if path.read_text(encoding="utf-8") == content:
            if (path.stat().st_mode & 0o777) != mode:
                os.chmod(str(path), mode)
            return False
    except (OSError, UnicodeDecodeError):
        pass
    fd, tmp = tempfile.mkstemp(prefix="." + path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
        os.chmod(tmp, mode)
        os.replace(tmp, str(path))
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise
    return True


def build_plan(root, warn):
    upstreams = read_proxy_list(root / "proxyList.txt", False, warn)
    public = read_proxy_list(root / "publicProxyList.txt", True, warn)
    combined = dedupe(upstreams + public, warn)
    upstreams = [u for u in combined if not u.public_list]
    public = [u for u in combined if u.public_list]
    vpns = discover_vpns(root / "openvpn", warn)
    allowlist = read_allowlist(root / "template" / "allowed_ip.txt", warn)
    users = read_users(root / "template" / "users.txt", warn)
    if not upstreams and not public and not vpns:
        raise InputError(
            "no usable upstream found: add proxies to proxyList.txt or VPN "
            "configs under openvpn/<name>/")
    return Plan(upstreams, public, vpns, allowlist, users)


def generate(root, nodes_only=False, resolve=True, resolver=default_resolver,
             warn=None, info=None):
    """Generate all outputs below `root`.  Returns {relative path: changed}."""
    root = Path(root)
    warn = warn or (lambda msg: print("warning: " + msg, file=sys.stderr))
    info = info or (lambda msg: print(msg))
    written = {}

    def put(rel, content, mode=0o644):
        written[rel] = write_file(root / rel, content, mode)

    if nodes_only:
        # users.txt is not needed for nodes.json, but it decides gost.yaml,
        # which is compared to detect that a full run is needed.
        plan = build_plan(root, warn)
        put("config/nodes.json", render_nodes_json(plan), 0o600)
        current = root / "config" / "gost.yaml"
        if not current.is_file() or \
                current.read_text(encoding="utf-8") != render_gost_yaml(plan):
            warn("config/gost.yaml is out of date (static ports, VPNs or "
                 "users changed): run 'python3 setup/generate.py' and "
                 "'docker compose up -d'")
        info("config/nodes.json: {} upstream(s) in the rotating pool{}".format(
            len(plan.pool), "" if written["config/nodes.json"] else " (unchanged)"))
        return written

    plan = build_plan(root, warn)
    vpn_conf_texts = {}
    gluetun_confs = {}
    for vpn in plan.vpns:
        if vpn.needs_resolved_copy and resolve:
            text = render_gluetun_conf(vpn, resolver)
            gluetun_confs[vpn.index] = text
        else:
            if vpn.needs_resolved_copy:
                warn("openvpn/{}: --no-resolve: remote hostname(s) {} kept; "
                     "gluetun will refuse to start with them".format(
                         vpn.dirname, ", ".join(vpn.hostnames)))
            text = vpn.ovpn.read_text(encoding="utf-8", errors="replace")
        vpn_conf_texts[vpn.index] = text
        if vpn.remote_count > 1:
            warn("openvpn/{}: {} remote lines; gluetun only uses the first "
                 "one".format(vpn.dirname, vpn.remote_count))

    gost_yaml = render_gost_yaml(plan)
    compose = HEADER + to_yaml(compose_config(
        plan, gost_yaml, vpn_conf_texts, set(gluetun_confs)))

    put("config/gost.yaml", gost_yaml, 0o600)
    put("config/nodes.json", render_nodes_json(plan), 0o600)
    put("config/allowed_ip.txt", render_allowlist(plan))
    put("config/users.txt", render_users(plan), 0o600)
    for vpn in plan.vpns:
        base = "openvpn/{}/".format(vpn.dirname)
        if vpn.secret is not None:
            put(base + "gluetun.env", render_gluetun_env(vpn), 0o600)
        if vpn.index in gluetun_confs:
            put(base + "gluetun.conf", gluetun_confs[vpn.index], 0o600)
    put("docker-compose.yml", compose)

    if (root / "config" / "squid.conf").exists():
        info("note: config/squid.conf is left over from the Squid version "
             "and can be deleted")
    _summary(plan, written, info)
    return written


def _summary(plan, written, info):
    info("Rotating port {}: {} upstream(s) in the pool ({} from proxyList.txt, "
         "{} from publicProxyList.txt, {} VPN)".format(
             ROTATE_PORT, len(plan.pool), len(plan.upstreams), len(plan.public),
             len(plan.vpns)))
    for port, _, desc in plan.static:
        info("Static port {}: {}".format(port, desc))
    info("Client allowlist: {} entr{}".format(
        len(plan.allowlist), "y" if len(plan.allowlist) == 1 else "ies"))
    if plan.auth_enabled:
        info("Client auth: enabled ({} user(s) from template/users.txt)".format(
            len(plan.users)))
    else:
        info("Client auth: disabled (template/users.txt has no users)")
    for rel in sorted(written):
        info("  {} {}".format("wrote    " if written[rel] else "unchanged", rel))
    # Data files are hot-reloaded by gost; everything else is applied by
    # `docker compose up -d` (gost.yaml via the hash label, gluetun.env via
    # env_file, gluetun.conf via its hash label).
    hot = {"config/nodes.json", "config/allowed_ip.txt", "config/users.txt"}
    if any(changed for rel, changed in written.items() if rel not in hot):
        info("Next: docker compose up -d")
    else:
        info("Nothing that needs a restart changed (gost reloads the data "
             "files within {}).".format(RELOAD))


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate gost/gluetun configuration for "
                    "docker-rotating-proxy.")
    parser.add_argument(
        "--root", default=str(Path(__file__).resolve().parent.parent),
        help="repository root (default: the parent of setup/)")
    parser.add_argument(
        "--nodes-only", action="store_true",
        help="only rewrite config/nodes.json from proxyList.txt + "
             "publicProxyList.txt + openvpn/ (no restart needed)")
    parser.add_argument(
        "--no-resolve", action="store_true",
        help="do not resolve hostnames in .ovpn 'remote' lines (offline/CI "
             "use; gluetun refuses hostnames)")
    args = parser.parse_args(argv)
    try:
        generate(args.root, nodes_only=args.nodes_only,
                 resolve=not args.no_resolve)
    except InputError as exc:
        print("error: {}".format(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
