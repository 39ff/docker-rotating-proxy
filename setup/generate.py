def _validate_host(host: str, bracketed: bool) -> str:
    if not host:
        raise LineError("empty host")
    if bracketed:
        try:
            ip = ipaddress.ip_address(host)
        except ValueError:
            raise LineError("%r is not an IPv6 address" % host)
        if ip.version != 6:
            raise LineError("brackets are only for IPv6 addresses, got %r" % host)
        return ip.compressed
    try:
        ip = ipaddress.ip_address(host)
    except ValueError:
        pass
    else:
        if ip.version == 6:
            raise LineError("IPv6 hosts must be written in brackets, e.g. [%s]:8080" % host)
        return ip.compressed
    if not _HOSTNAME.match(host) or ".." in host:
        raise LineError("invalid host %r" % host)
    return host.lower()


def _starts_with_bare_ipv6(text: str) -> bool:
    pieces = text.split(":")
    for n in range(len(pieces), 2, -1):
        try:
            if ipaddress.ip_address(":".join(pieces[:n])).version == 6:
                return True
        except ValueError:
            continue
    return False


def _validate_port(text: str) -> int:
    if not text.isascii() or not text.isdigit():
        raise LineError("invalid port %r" % text)
    port = int(text)
    if not 1 <= port <= 65535:
        raise LineError("port %d out of range 1-65535" % port)
    return port


def _validate_cred(value: str, what: str) -> str:
    if _FORBIDDEN_CRED.search(value):
        raise LineError("%s contains whitespace, a quote, '#' or a control character" % what)
    return value


def parse_proxy_line(line: str, source: str = "") -> Optional[Upstream]:
    """Parse one proxy list line. Returns None for blank/comment lines.

    Format: host:port[:scheme[:user:pass]] ; IPv6 hosts as [addr]:port.
    The password is everything after the fourth ':' and may contain ':'.
    """
    text = line.strip().lstrip("\ufeff")
    if not text or text.startswith("#"):
        return None
    if text.startswith("["):
        end = text.find("]")
        if end < 0:
            raise LineError("missing ']' after IPv6 address")
        host_raw = text[1:end]
        rest = text[end + 1:]
        if not rest.startswith(":"):
            raise LineError("expected ':port' after ']'")
        parts = rest[1:].split(":", 3)
        bracketed = True
    else:
        if _starts_with_bare_ipv6(text):
            raise LineError("IPv6 hosts must be written in brackets, e.g. [2001:db8::1]:8080")
        first, sep, rest = text.partition(":")
        if not sep:
            raise LineError("expected host:port")
        host_raw = first
        parts = rest.split(":", 3)
        bracketed = False
    parts += [""] * (4 - len(parts))
    port_raw, scheme, user, password = parts
    host = _validate_host(host_raw, bracketed)
    port = _validate_port(port_raw)
    scheme = scheme.strip().lower()
    if scheme not in SCHEMES:
        raise LineError("unknown scheme %r (use socks5, http, https, httpsquid or leave empty)" % scheme)
    _validate_cred(user, "username")
    _validate_cred(password, "password")
    if password and not user:
        raise LineError("password given without username")
    if not scheme and user:
        raise LineError("credentials need a scheme (use httpsquid for an authenticated HTTP proxy)")
    if ":" in user:
        raise LineError("username must not contain ':'")
    return Upstream(host=host, port=port, scheme=scheme, user=user, password=password, source=source)


def read_lines(path: Path) -> List[str]:
    with open(path, "r", encoding="utf-8", errors="replace", newline=None) as fh:
        return fh.read().splitlines()


def parse_proxy_file(path: Path, rep: Reporter, public_only: bool = False) -> List[Upstream]:
    result: List[Upstream] = []
    if not path.is_file():
        return result
    for lineno, line in enumerate(read_lines(path), 1):
        source = "%s:%d" % (path.name, lineno)
        try:
            up = parse_proxy_line(line, source)
        except LineError as exc:
            rep.warn("%s: skipped: %s" % (source, exc), path.name)
            continue
        if up is None:
            continue
        if public_only and up.scheme:
            rep.warn("%s: skipped: %s only takes host:port lines (public proxies); "
                     "put proxies with a scheme into proxyList.txt" % (source, path.name), path.name)
            continue
        result.append(up)
    return result


def parse_allowlist(path: Path, rep: Reporter) -> List[str]:
    entries: List[str] = []
    seen = set()
    if not path.is_file():
        rep.warn("%s not found: nobody will be allowed to use the proxy" % path)
        return entries
    for lineno, line in enumerate(read_lines(path), 1):
        text = line.split("#", 1)[0].strip()
        if not text:
            continue
        try:
            if "/" in text:
                value = str(ipaddress.ip_network(text, strict=False))
            else:
                value = str(ipaddress.ip_address(text))
        except ValueError:
            rep.warn("%s:%d: skipped: %r is not an IP address or CIDR" % (path.name, lineno, text), path.name)
            continue
        if value in seen:
            continue
        seen.add(value)
        entries.append(value)
    if not entries:
        rep.warn("%s has no valid entries: nobody will be allowed to use the proxy" % path.name)
    for value in entries:
        if value in ("0.0.0.0/0", "::/0"):
            rep.warn("allowlist contains %s: the proxy is open to everyone who can reach it" % value)
    return entries


def read_secret(path: Path, rep: Reporter) -> Tuple[Optional[str], Optional[str]]:
    lines = [ln for ln in read_lines(path) if ln.strip()]
    if len(lines) < 2:
        rep.warn("%s: expected username on line 1 and password on line 2; credentials ignored" % path)
        return None, None
    user, password = lines[0], lines[1]
    if "\x00" in user or "\x00" in password:
        rep.warn("%s: NUL character in credentials; credentials ignored" % path)
        return None, None
    return user, password


def ovpn_remote_hostnames(path: Path) -> List[str]:
    """Hostnames (not IP literals) used in `remote` lines of an .ovpn file."""
    hosts: List[str] = []
    for line in read_lines(path):
        stripped = line.strip()
        if stripped.startswith(("#", ";")):
            continue
        m = _REMOTE.match(stripped)
        if not m:
            continue
        host = m.group(2)
        try:
            ipaddress.ip_address(host)
        except ValueError:
            if host not in hosts:
                hosts.append(host)
    return hosts


def discover_vpns(openvpn_dir: Path, rep: Reporter) -> List[Vpn]:
    vpns: List[Vpn] = []
    if not openvpn_dir.is_dir():
        return vpns
    for entry in sorted(openvpn_dir.iterdir(), key=lambda p: p.name):
        if not entry.is_dir() or entry.name.startswith("."):
            continue
        if not _SAFE_NAME.match(entry.name):
            rep.warn("openvpn/%s: skipped: directory names may only contain letters, digits, '.', '_' and '-'"
                     % entry.name)
            continue
        ovpns = sorted(p for p in entry.glob("*.ovpn") if p.is_file())
        if not ovpns:
            rep.warn("openvpn/%s: skipped: no .ovpn file found" % entry.name)
            continue
        if len(ovpns) > 1:
            rep.warn("openvpn/%s: several .ovpn files, using %s" % (entry.name, ovpns[0].name))
        ovpn = ovpns[0]
        if not _SAFE_NAME.match(ovpn.name):
            rep.warn("openvpn/%s: skipped: file name %r may only contain letters, digits, '.', '_' and '-'"
                     % (entry.name, ovpn.name))
            continue
        vpn = Vpn(index=len(vpns) + 1, name=entry.name, ovpn=ovpn, remote_hosts=ovpn_remote_hostnames(ovpn))
        secret = entry / "secret"
        if secret.is_file():
            vpn.user, vpn.password = read_secret(secret, rep)
        vpns.append(vpn)
    return vpns


