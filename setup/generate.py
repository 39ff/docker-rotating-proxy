# gost configuration


def upstream_node(name, upstream):
    connector = {"type": "socks5" if upstream.scheme == "socks5" else "http"}
    if upstream.username:
        connector["auth"] = {"username": upstream.username,
                             "password": upstream.password}
    dialer = {"type": "tls" if upstream.scheme == "https" else "tcp"}
    return {"name": name, "addr": upstream.addr, "connector": connector,
            "dialer": dialer}


def vpn_node(vpn):
    return {"name": vpn.node_name, "addr": vpn.addr,
            "connector": {"type": "http"}, "dialer": {"type": "tcp"}}


class Plan:
    """Everything derived from the inputs, before anything is written."""

    def __init__(self, upstreams, public, vpns, allowlist, users):
        self.upstreams = upstreams
        self.public = public
        self.vpns = vpns
        self.allowlist = allowlist
        self.users = users

        # Rotating pool order: proxyList.txt, VPNs, publicProxyList.txt.
        # Static ports: socks5/http/https lines of proxyList.txt in file
        # order, then one per VPN directory (sorted by name).
        self.pool = []      # node configs for config/nodes.json
        fixed = []          # (node config, description)
        for number, upstream in enumerate(upstreams, 1):
            node = upstream_node("proxy-{}".format(number), upstream)
            self.pool.append(node)
            if upstream.has_static_port:
                fixed.append((node, upstream.describe()))
        for vpn in vpns:
            node = vpn_node(vpn)
            self.pool.append(node)
            fixed.append((node, "vpn openvpn/{}".format(vpn.dirname)))
        for number, upstream in enumerate(public, 1):
            self.pool.append(upstream_node("public-{}".format(number), upstream))
        self.static = [(STATIC_BASE_PORT + i, node, desc)
                       for i, (node, desc) in enumerate(fixed)]
        if self.static and self.static[-1][0] > 65535:
            raise InputError("too many static ports ({}): the last one would be "
                             "{}".format(len(self.static), self.static[-1][0]))

    @property
    def auth_enabled(self):
        return bool(self.users)


def _service(name, port, chain, auth_enabled, retries=0):
    handler = {"type": "http", "chain": chain}
    if retries:
        handler["retries"] = retries
    if auth_enabled:
        handler["auther"] = "users"
    return {
        "name": name,
        "addr": ":{}".format(port),
        "admission": "allowlist",
        "handler": handler,
        "listener": {"type": "tcp"},
        "metadata": {"dialTimeout": "10s"},
    }


def gost_config(plan):
    config = {
        "log": {"level": "info"},
        "metrics": {"addr": METRICS_ADDR, "path": "/metrics"},
        "admissions": [{
            # whitelist: true is essential - gost's default mode is blacklist.
            "name": "allowlist",
            "whitelist": True,
            "reload": RELOAD,
            "file": {"path": CONFIG_IN_CONTAINER + "/allowed_ip.txt"},
        }],
    }
    if plan.auth_enabled:
        config["authers"] = [{
            "name": "users",
            "reload": RELOAD,
            "file": {"path": CONFIG_IN_CONTAINER + "/users.txt"},
        }]
    config["hops"] = [{
        "name": "upstreams",
        "selector": {"strategy": "round", "maxFails": 2, "failTimeout": "60s"},
        "reload": RELOAD,
        "file": {"path": CONFIG_IN_CONTAINER + "/nodes.json"},
        "nodes": [{
            "name": "fail-closed",
            "addr": FAIL_CLOSED_ADDR,
            "connector": {"type": "http"},
            "dialer": {"type": "tcp"},
            "metadata": {"backup": True},
        }],
    }]
    chains = [{"name": "pool", "hops": [{"name": "upstreams"}]}]
    services = [_service("rotate", ROTATE_PORT, "pool", plan.auth_enabled,
                         retries=2)]
    for port, node, _ in plan.static:
        name = "static-{}".format(port)
        chains.append({"name": name, "hops": [{"name": name, "nodes": [node]}]})
        services.append(_service(name, port, name, plan.auth_enabled))
    config["chains"] = chains
    config["services"] = services
    return config


def render_gost_yaml(plan):
    comment = (
        "#\n"
        "# Port {}: rotating pool (config/nodes.json, hot-reloaded every {}).\n"
        "# Ports {}+: one fixed upstream each (changes need a restart).\n"
        "# allowed_ip.txt and users.txt are hot-reloaded every {} as well.\n"
    ).format(ROTATE_PORT, RELOAD, STATIC_BASE_PORT, RELOAD)
    lines = []
    for port, _, desc in plan.static:
        lines.append("#   {} -> {}\n".format(port, desc))
    return HEADER + comment + "".join(lines) + to_yaml(gost_config(plan))


def render_nodes_json(plan):
    if not plan.pool:
        return "[]\n"
    return "[\n" + ",\n".join(
        "  " + json.dumps(node, ensure_ascii=True) for node in plan.pool
    ) + "\n]\n"


def render_allowlist(plan):
    return ("# Generated by setup/generate.py from template/allowed_ip.txt.\n"
            + "".join(entry + "\n" for entry in plan.allowlist))


def render_users(plan):
    text = ("# Generated by setup/generate.py from template/users.txt.\n"
            "# Contains credentials: never commit this file.\n")
    return text + "".join("{} {}\n".format(u, p) for u, p in plan.users)


def _sha256(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def compose_config(plan, gost_yaml, vpn_conf_texts, resolved_copies):
    """docker-compose.yml content.

    vpn_conf_texts: {vpn index: text of the file mounted as custom.conf}
    resolved_copies: indexes of VPNs that mount the generated gluetun.conf
    """
    bind = "${BIND_ADDR:-0.0.0.0}"
    ports = ["{}:{}:{}".format(bind, ROTATE_PORT, ROTATE_PORT)]
    ports += ["{}:{}:{}".format(bind, port, port) for port, _, _ in plan.static]
    gost = {
        "image": GOST_IMAGE,
        "container_name": GOST_CONTAINER,
        "restart": "unless-stopped",
        "command": ["-C", CONFIG_IN_CONTAINER + "/gost.yaml"],
        "volumes": ["./config:{}:ro".format(CONFIG_IN_CONTAINER)],
        "ports": ports,
        "extra_hosts": ["host.docker.internal:host-gateway"],
        "ulimits": {"nofile": {"soft": 65536, "hard": 65536}},
        # Changes whenever gost.yaml changes, so `docker compose up -d`
        # recreates the container (gost does not reload its main config).
        "labels": {HASH_LABEL: _sha256(gost_yaml)},
        "healthcheck": {
            "test": ["CMD", "wget", "-q", "-O", "/dev/null",
                     "http://{}/metrics".format(METRICS_ADDR)],
            "interval": "30s",
            "timeout": "5s",
            "retries": 3,
            "start_period": "10s",
        },
        "logging": LOGGING,
    }
    if plan.vpns:
        gost["depends_on"] = [vpn.service for vpn in plan.vpns]
    services = {"gost": gost}
    for vpn in plan.vpns:
        directory = "./openvpn/{}".format(vpn.dirname)
        mounted = "gluetun.conf" if vpn.index in resolved_copies else vpn.ovpn.name
        service = {
            "image": GLUETUN_IMAGE,
            "container_name": vpn.container,
            "restart": "unless-stopped",
            "cap_add": ["NET_ADMIN"],
            "devices": ["/dev/net/tun:/dev/net/tun"],
        }
        if vpn.secret is not None:
            service["env_file"] = [directory + "/gluetun.env"]
        service["environment"] = {
            "VPN_SERVICE_PROVIDER": "custom",
            "VPN_TYPE": "openvpn",
            "OPENVPN_CUSTOM_CONFIG": "/gluetun/custom.conf",
            "HTTPPROXY": "on",
            "HTTPPROXY_STEALTH": "on",
            "HTTPPROXY_LISTENING_ADDRESS": ":{}".format(GLUETUN_HTTP_PORT),
        }
        service["volumes"] = ["{}/{}:/gluetun/custom.conf:ro".format(
            directory, mounted)]
        service["labels"] = {HASH_LABEL: _sha256(vpn_conf_texts[vpn.index])}
        service["logging"] = LOGGING
        services[vpn.service] = service
    return {"services": services}


