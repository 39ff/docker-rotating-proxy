#!/usr/bin/env python3
"""Generate the rotating proxy configuration.

Reads (relative to the repository root):
  proxyList.txt            host:port[:scheme[:user:pass]] per line
  publicProxyList.txt      optional, host:port per line (public proxies)
  openvpn/<name>/*.ovpn    one OpenVPN client config per directory
  openvpn/<name>/secret    optional, line 1 = username, line 2 = password
  template/squid.conf      Squid template (cache_peer lines are inserted)
  template/allowed_ip.txt  client allowlist (one IP or CIDR per line)

Writes:
  config/squid.conf, config/gost.yaml, config/allowed_ip.txt,
  docker-compose.yml, openvpn/<name>/gluetun.env (and, when the .ovpn uses a
  hostname in its `remote` line, openvpn/<name>/gluetun.conf).

Python 3.8+ standard library only. Run `python3 setup/generate.py --help`.
"""

