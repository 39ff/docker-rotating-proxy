def read_allowlist(path, warn):
    if not path.is_file():
        raise InputError(
            "{} is missing: without an allowlist nobody can use the "
            "proxy".format(path))
    entries = []
    for lineno, raw in enumerate(
            path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        try:
            if "/" in line:
                network = ipaddress.ip_network(line, strict=False)
                if str(network) != line:
                    warn("{}:{}: {} normalised to {}".format(
                        path.name, lineno, line, network))
                value = str(network)
            else:
                value = str(ipaddress.ip_address(line))
        except ValueError:
            warn("{}:{}: skipped: not an IP address or CIDR: {!r}".format(
                path.name, lineno, line))
            continue
        if value not in entries:
            entries.append(value)
    if not entries:
        raise InputError(
            "{} has no valid entry: nobody could use the proxy. Add at least "
            "127.0.0.1 (or 0.0.0.0/0 together with template/users.txt).".format(
                path))
    return entries


def read_users(path, warn):
    if not path.is_file():
        return []
    users = []
    names = set()
    for lineno, raw in enumerate(
            path.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(None, 1)
        where = "{}:{}".format(path.name, lineno)
        if len(parts) != 2:
            warn("{}: skipped: expected 'username password'".format(where))
            continue
        user, password = parts
        if ":" in user or _BAD_CRED_RE.search(user):
            warn("{}: skipped: username must not contain ':', quotes or "
                 "control characters".format(where))
            continue
        if _BAD_CRED_RE.search(password):
            warn("{}: skipped: password must not contain whitespace, quotes "
                 "or backslashes".format(where))
            continue
        if user in names:
            warn("{}: skipped: duplicate username {!r}".format(where, user))
            continue
        names.add(user)
        users.append((user, password))
    return users


