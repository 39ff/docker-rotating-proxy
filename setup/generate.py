@dataclass(frozen=True)
class Upstream:
    host: str  # without brackets, IPv6 literal or IPv4 or hostname
    port: int
    scheme: str
    user: str = ""
    password: str = ""
    source: str = ""  # "proxyList.txt:3"

    @property
    def is_ipv6(self) -> bool:
        return ":" in self.host

    @property
    def hostport(self) -> str:
        """host:port as understood by Go (gost) and curl."""
        return "[%s]:%d" % (self.host, self.port) if self.is_ipv6 else "%s:%d" % (self.host, self.port)

    @property
    def has_auth(self) -> bool:
        return bool(self.user)

    def describe(self) -> str:
        scheme = self.scheme or "public http"
        return "%s %s (%s)" % (scheme, self.hostport, self.source)


@dataclass
class Vpn:
    index: int  # 1-based, dockervpn_<index>
    name: str  # directory name under openvpn/
    ovpn: Path  # user's .ovpn file (never modified)
    remote_hosts: List[str]  # hostnames used in `remote` lines (need resolving)
    user: Optional[str] = None
    password: Optional[str] = None

    @property
    def container(self) -> str:
        return VPN_CONTAINER.format(self.index)

    @property
    def service(self) -> str:
        return "vpn%d" % self.index

    @property
    def needs_derived_config(self) -> bool:
        return bool(self.remote_hosts)

    def mount_source(self) -> str:
        if self.needs_derived_config:
            return "./openvpn/%s/gluetun.conf" % self.name
        return "./openvpn/%s/%s" % (self.name, self.ovpn.name)


@dataclass
class StaticPort:
    port: int
    index: int  # 1-based, static-<index>
    chain: str
    description: str


@dataclass
class Plan:
    squid_peers: List[str] = field(default_factory=list)
    squid_peers_fixed: List[str] = field(default_factory=list)  # without publicProxyList.txt
    static_ports: List[StaticPort] = field(default_factory=list)
    gost: Dict = field(default_factory=dict)
    vpns: List[Vpn] = field(default_factory=list)
    counts: Dict[str, int] = field(default_factory=dict)


class Reporter:
    """Collects warnings, prints at most `limit` per source file."""

    def __init__(self, stream=None, limit: int = 20, quiet: bool = False):
        self.stream = stream if stream is not None else sys.stderr
        self.limit = limit
        self.quiet = quiet
        self.warnings: List[str] = []
        self._per_source: Dict[str, int] = {}

    def warn(self, msg: str, source: str = "") -> None:
        self.warnings.append(msg)
        n = self._per_source.get(source, 0) + 1
        self._per_source[source] = n
        if n <= self.limit:
            self.stream.write("warning: %s\n" % msg)
        elif n == self.limit + 1:
            self.stream.write("warning: %s: further warnings suppressed\n" % (source or "generator"))

    def info(self, msg: str) -> None:
        if not self.quiet:
            self.stream.write(msg + "\n")

    def summary(self) -> None:
        hidden = sum(max(0, n - self.limit) for n in self._per_source.values())
        if hidden:
            self.stream.write("warning: %d more warning(s) not shown\n" % hidden)


