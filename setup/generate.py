#!/usr/bin/env python3
"""Generate the docker-rotating-proxy configuration (gost v3 + gluetun).

Python 3.9+ standard library only.  Run from anywhere:

    python3 setup/generate.py                 # full generation
    python3 setup/generate.py --nodes-only    # only config/nodes.json (cron)

or without a local Python:

    docker run --rm --user "$(id -u):$(id -g)" -v "$PWD:/app" -w /app \
        python:3.13-alpine python3 setup/generate.py

Inputs (relative to the repository root):
    proxyList.txt               upstream proxies, one per line (see README)
    publicProxyList.txt         optional, written by public_proxy_cron.sh;
                                its entries only join the rotating pool
    openvpn/<name>/<file>.ovpn  one OpenVPN config per directory
    openvpn/<name>/secret       optional: line 1 user, line 2 password
    template/allowed_ip.txt     client allowlist (IP or CIDR per line)
    template/users.txt          optional client credentials ("user password")

Outputs:
    config/gost.yaml            gost main config (restart needed on change)
    config/nodes.json           rotating pool (hot-reloaded by gost)
    config/allowed_ip.txt       normalised allowlist (hot-reloaded)
    config/users.txt            normalised credentials (hot-reloaded)
    docker-compose.yml
    openvpn/<name>/gluetun.env  OPENVPN_USER / OPENVPN_PASSWORD for gluetun
    openvpn/<name>/gluetun.conf only when the .ovpn has `remote <hostname>`:
                                a copy with the hostname resolved to an IP,
                                because gluetun's custom provider only accepts
                                IP addresses.  The original is never modified.
"""

