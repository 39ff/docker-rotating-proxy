def squid_login(user: str, password: str) -> str:
    """Value for cache_peer login=.

    Squid runs rfc1738_unescape() over the login= value, so %XX escapes are
    decoded before the Basic credentials are built.  Percent-encoding every
    byte outside [A-Za-z0-9_.~-] keeps squid.conf tokenisation and Squid's
    ${macro} expansion away from the credentials.  (PHP's urlencode() used by
    the old generator turned spaces into '+', which Squid does not decode.)
    """
    return "%s:%s" % (urllib.parse.quote(user, safe=""), urllib.parse.quote(password, safe=""))


def squid_peer(host: str, port: int, name: str, extra: Sequence[str] = ()) -> str:
    line = "cache_peer %s parent %d 0 %s name=%s" % (host, port, PEER_OPTIONS, name)
    if extra:
        line += " " + " ".join(extra)
    return line


_YAML_KEY = re.compile(r"^[A-Za-z_][A-Za-z0-9_.-]*$")


def _yaml_scalar(value) -> str:
    if value is True:
        return "true"
    if value is False:
        return "false"
    if value is None:
        return "null"
    if isinstance(value, int):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def _yaml_key(key: str) -> str:
    return key if _YAML_KEY.match(key) else json.dumps(key, ensure_ascii=False)


def _is_scalar(value) -> bool:
    return not isinstance(value, (dict, list))


def to_yaml(obj, indent: int = 0) -> List[str]:
    """Tiny YAML emitter: block mappings/sequences, JSON-quoted strings."""
    pad = "  " * indent
    lines: List[str] = []
    if isinstance(obj, dict):
        for key, value in obj.items():
            k = _yaml_key(str(key))
            if isinstance(value, dict) and value:
                lines.append("%s%s:" % (pad, k))
                lines.extend(to_yaml(value, indent + 1))
            elif isinstance(value, list) and value:
                flow = _flow_list(value)
                if flow is not None and len(pad) + len(k) + len(flow) < 100:
                    lines.append("%s%s: %s" % (pad, k, flow))
                else:
                    lines.append("%s%s:" % (pad, k))
                    lines.extend(to_yaml(value, indent + 1))
            elif isinstance(value, dict):
                lines.append("%s%s: {}" % (pad, k))
            elif isinstance(value, list):
                lines.append("%s%s: []" % (pad, k))
            else:
                lines.append("%s%s: %s" % (pad, k, _yaml_scalar(value)))
    elif isinstance(obj, list):
        for item in obj:
            if isinstance(item, dict) and item:
                sub = to_yaml(item, indent + 1)
                lines.append("%s- %s" % (pad, sub[0][len(pad) + 2:]))
                lines.extend(sub[1:])
            elif isinstance(item, list) and item:
                flow = _flow_list(item)
                if flow is None:
                    raise ValueError("nested non-scalar lists are not supported")
                lines.append("%s- %s" % (pad, flow))
            else:
                lines.append("%s- %s" % (pad, _yaml_scalar(item) if _is_scalar(item) else "{}"))
    else:
        lines.append(pad + _yaml_scalar(obj))
    return lines


def _flow_list(values: list) -> Optional[str]:
    if all(_is_scalar(v) for v in values):
        return "[" + ", ".join(_yaml_scalar(v) for v in values) + "]"
    return None


def dump_yaml(obj, header: Sequence[str] = ()) -> str:
    out = ["# " + h if h else "#" for h in header]
    out.extend(to_yaml(obj))
    return "\n".join(out) + "\n"


def dotenv_quote(value: str) -> str:
    """Quote a value for a docker compose env_file (no interpolation)."""
    if "'" not in value and "\n" not in value:
        return "'%s'" % value
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "$$").replace("\n", "\\n")
    return '"%s"' % escaped


