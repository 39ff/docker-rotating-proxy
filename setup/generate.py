def _gost_node(up: Upstream, name: str) -> Dict:
    connector: Dict = {"type": "socks5" if up.scheme == "socks5" else "http"}
    if up.has_auth:
        connector["auth"] = {"username": up.user, "password": up.password}
    dialer: Dict = {"type": "tcp"}
    if up.scheme == "https":
        # Verify the upstream certificate (serverName defaults to the host).
        dialer = {"type": "tls", "tls": {"secure": True, "serverName": up.host}}
    return {"name": name, "addr": up.hostport, "connector": connector, "dialer": dialer}


def _gost_service(name: str, port: int, chain: str, admission: Optional[str]) -> Dict:
    svc: Dict = {"name": name, "addr": ":%d" % port}
    if admission:
        svc["admission"] = admission
    svc["handler"] = {"type": "http", "chain": chain}
    svc["listener"] = {"type": "tcp"}
    return svc


def dedupe(upstreams: List[Upstream], public: List[Upstream], rep: Reporter) -> Tuple[List[Upstream], List[Upstream]]:
    seen_exact = set()
    seen_hostport = set()
    uniq: List[Upstream] = []
    for up in upstreams:
        key = (up.host, up.port, up.scheme, up.user, up.password)
        if key in seen_exact:
            rep.warn("%s: skipped: duplicate of an earlier line" % up.source, "proxyList.txt")
            continue
        seen_exact.add(key)
        seen_hostport.add((up.host, up.port))
        uniq.append(up)
    pub: List[Upstream] = []
    dupes = 0
    for up in public:
        if (up.host, up.port) in seen_hostport:
            dupes += 1
            continue
        seen_hostport.add((up.host, up.port))
        pub.append(up)
    if dupes:
        rep.info("public proxies: %d duplicate host:port entries ignored" % dupes)
    return uniq, pub


def build_plan(upstreams: List[Upstream], public: List[Upstream], vpns: List[Vpn],
               allowlist_path_in_container: str = GOST_CONF_DIR + "/allowed_ip.txt") -> Plan:
    plan = Plan(vpns=list(vpns))
    counts = {"public": 0, "private": 0, "gost": 0, "https": 0, "vpn": 0}
    services: List[Dict] = []
    chains: List[Dict] = []
    static_index = 0
    public_index = 0
    private_index = 0

    for up in upstreams:
        if up.scheme == "":
            public_index += 1
            counts["public"] += 1
            plan.squid_peers.append(squid_peer(up.host, up.port, "public%d" % public_index))
            continue
        if up.scheme == "httpsquid":
            private_index += 1
            counts["private"] += 1
            extra = ["login=" + squid_login(up.user, up.password)] if up.has_auth else []
            plan.squid_peers.append(squid_peer(up.host, up.port, "private%d" % private_index, extra))
            continue
        # socks5 / http / https: one chain, one static port, maybe one peer port.
        static_index += 1
        n = static_index
        chain = "chain-%d" % n
        chains.append({"name": chain, "hops": [{"name": "hop-%d" % n, "nodes": [_gost_node(up, "upstream-%d" % n)]}]})
        static_port = STATIC_BASE_PORT + n - 1
        if up.scheme in GOST_SCHEMES:
            counts["gost"] += 1
            peer_port = PEER_BASE_PORT + n - 1
            services.append(_gost_service("peer-%d" % n, peer_port, chain, None))
            plan.squid_peers.append(squid_peer(GOST_CONTAINER, peer_port, "gost%d" % n))
        else:  # https: Squid talks TLS to the upstream itself (issue #23)
            counts["https"] += 1
            # tls-min-version=1.2 alone makes Squid 7.5/7.6 log "ERROR: Unknown TLS option".
            extra = ["tls", "tls-options=NO_SSLv3,NO_TLSv1,NO_TLSv1_1"]
            if up.has_auth:
                extra.append("login=" + squid_login(up.user, up.password))
            plan.squid_peers.append(squid_peer(up.host, up.port, "https%d" % n, extra))
        services.append(_gost_service("static-%d" % n, static_port, chain, "allowlist"))
        plan.static_ports.append(StaticPort(static_port, n, chain, up.describe()))

    for vpn in vpns:
        static_index += 1
        n = static_index
        counts["vpn"] += 1
        plan.squid_peers.append(squid_peer(vpn.container, GLUETUN_HTTP_PORT, "vpn%d" % vpn.index))
        chain = "chain-%d" % n
        node = {"name": "upstream-%d" % n, "addr": "%s:%d" % (vpn.container, GLUETUN_HTTP_PORT),
                "connector": {"type": "http"}, "dialer": {"type": "tcp"}}
        chains.append({"name": chain, "hops": [{"name": "hop-%d" % n, "nodes": [node]}]})
        static_port = STATIC_BASE_PORT + n - 1
        services.append(_gost_service("static-%d" % n, static_port, chain, "allowlist"))
        plan.static_ports.append(StaticPort(static_port, n, chain, "vpn openvpn/%s (%s)" % (vpn.name, vpn.container)))

    plan.squid_peers_fixed = list(plan.squid_peers)
    for up in public:
        public_index += 1
        counts["public"] += 1
        plan.squid_peers.append(squid_peer(up.host, up.port, "public%d" % public_index))

    if static_index > MAX_STATIC_PORTS:
        raise SystemExit("error: %d static ports requested, at most %d are supported" % (static_index, MAX_STATIC_PORTS))

    # Static services first (easier to read), then the internal peer services.
    services.sort(key=lambda s: (0 if s["name"].startswith("static-") else 1, int(s["name"].split("-")[1])))
    plan.gost = {
        "services": services,
        "chains": chains,
        "admissions": [{
            "name": "allowlist",
            "whitelist": True,  # gost's default is blacklist mode
            "reload": "30s",
            "file": {"path": allowlist_path_in_container},
        }],
        "log": {"level": "info", "format": "text"},
        "metrics": {"addr": GOST_METRICS_ADDR, "path": "/metrics"},
    }
    plan.counts = counts
    return plan


def render_squid_conf(template: str, peers: List[str]) -> str:
    block = "\n".join(peers)
    lines = template.splitlines()
    out: List[str] = ["# " + GENERATED_BY, "# Source: template/squid.conf", ""]
    replaced = False
    for line in lines:
        if line.strip() == PEERS_MARKER:
            out.append(block)
            replaced = True
        else:
            out.append(line)
    if not replaced:
        out.extend(["", block])
    return "\n".join(out).rstrip("\n") + "\n"


def render_gost_yaml(plan: Plan) -> str:
    header = [GENERATED_BY, "Contains upstream credentials: keep it private (it is gitignored).", ""]
    if plan.static_ports:
        header.append("Static ports (published, allowlisted):")
        for sp in plan.static_ports:
            header.append("  :%d -> %s" % (sp.port, sp.description))
    return dump_yaml(plan.gost, header)


CONFIG_HASH_LABEL = "rotating-proxy.config-hash"


def config_hash(*parts: str) -> str:
    digest = hashlib.sha256()
    for part in parts:
        digest.update(part.encode("utf-8", "surrogateescape"))
        digest.update(b"\0")
    return digest.hexdigest()[:16]


def build_compose(plan: Plan, hashes: Optional[Dict[str, str]] = None) -> Dict:
    """Compose model. `hashes` (service -> digest of its mounted config) become
    labels, so `docker compose up -d` recreates a service whose bind-mounted
    config changed (compose does not look at file contents itself)."""
    hashes = hashes or {}
    bind = "${BIND_ADDR:-0.0.0.0}"
    services: Dict = {}
    depends: List[str] = []
    if plan.static_ports:
        depends.append("gost")
    depends.extend(v.service for v in plan.vpns)

    squid: Dict = {
        "image": "${SQUID_IMAGE:-%s}" % SQUID_IMAGE,
        "container_name": SQUID_CONTAINER,
        "restart": "unless-stopped",
        "environment": {"SQUID_CONFIG_FILE": SQUID_CONF_DIR + "/squid.conf"},
        "volumes": ["./config:%s:ro" % SQUID_CONF_DIR],
        "ports": ["%s:%d:%d" % (bind, SQUID_PORT, SQUID_PORT)],
        "extra_hosts": ["host.docker.internal:host-gateway"],
        "ulimits": {"nofile": {"soft": 65536, "hard": 65536}},
        "healthcheck": {
            # Cache manager on localhost: proves Squid answers without touching an upstream.
            "test": ["CMD", "curl", "-fsS", "-o", "/dev/null",
                     "http://127.0.0.1:%d/squid-internal-mgr/info" % SQUID_PORT],
            "interval": "30s",
            "timeout": "5s",
            "retries": 3,
            "start_period": "15s",
        },
    }
    if depends:
        squid["depends_on"] = depends
    services["squid"] = squid

    if plan.static_ports:
        services["gost"] = {
            "image": GOST_IMAGE,
            "container_name": GOST_CONTAINER,
            "restart": "unless-stopped",
            "command": ["-C", GOST_CONF_DIR + "/gost.yaml"],
            "volumes": ["./config:%s:ro" % GOST_CONF_DIR],
            "ports": ["%s:%d:%d" % (bind, sp.port, sp.port) for sp in plan.static_ports],
            "extra_hosts": ["host.docker.internal:host-gateway"],
            "healthcheck": {
                "test": ["CMD", "wget", "-q", "-O", "/dev/null", "http://%s/metrics" % GOST_METRICS_ADDR],
                "interval": "30s",
                "timeout": "5s",
                "retries": 3,
                "start_period": "5s",
            },
        }
        if plan.vpns:
            services["gost"]["depends_on"] = [v.service for v in plan.vpns]

    for vpn in plan.vpns:
        svc: Dict = {
            "image": GLUETUN_IMAGE,
            "container_name": vpn.container,
            "restart": "unless-stopped",
            "cap_add": ["NET_ADMIN"],
            "devices": ["/dev/net/tun:/dev/net/tun"],
            "environment": {
                "VPN_SERVICE_PROVIDER": "custom",
                "VPN_TYPE": "openvpn",
                "OPENVPN_CUSTOM_CONFIG": GLUETUN_CUSTOM_CONFIG,
                "HTTPPROXY": "on",
                "HTTPPROXY_STEALTH": "on",
            },
            "volumes": ["%s:%s:ro" % (vpn.mount_source(), GLUETUN_CUSTOM_CONFIG)],
        }
        if vpn.user is not None:
            svc["env_file"] = ["./openvpn/%s/gluetun.env" % vpn.name]
        services[vpn.service] = svc

    for name, digest in sorted(hashes.items()):
        if name in services:
            services[name]["labels"] = {CONFIG_HASH_LABEL: digest}

    return {
        "services": services,
        "networks": {
            "default": {
                # Fixed subnet so that the gateway (the source address of
                # clients on the Docker host) is predictable for the allowlist.
                "ipam": {"config": [{"subnet": "${PROXY_SUBNET:-%s}" % DEFAULT_SUBNET}]},
            },
        },
    }


def render_compose(plan: Plan, hashes: Optional[Dict[str, str]] = None) -> str:
    header = [GENERATED_BY, "Settings via .env: BIND_ADDR (default 0.0.0.0), PROXY_SUBNET (default %s), "
              "SQUID_IMAGE." % DEFAULT_SUBNET, "Put local additions into docker-compose.override.yml.", ""]
    return dump_yaml(build_compose(plan, hashes), header)


def render_gluetun_env(vpn: Vpn) -> str:
    return ("# %s\n# Source: openvpn/%s/secret - keep private (gitignored).\n"
            "OPENVPN_USER=%s\nOPENVPN_PASSWORD=%s\n"
            % (GENERATED_BY, vpn.name, dotenv_quote(vpn.user or ""), dotenv_quote(vpn.password or "")))


Resolver = Callable[[str], Optional[str]]


def default_resolver(host: str) -> Optional[str]:
    try:
        infos = socket.getaddrinfo(host, None, socket.AF_INET, socket.SOCK_STREAM)
    except (socket.gaierror, UnicodeError, OSError):
        return None
    return infos[0][4][0] if infos else None


def render_gluetun_conf(vpn: Vpn, resolver: Resolver, rep: Reporter) -> str:
    """Copy of the user's .ovpn with `remote <hostname>` resolved to an IP.

    gluetun's custom provider (v3.41.3, internal/openvpn/extract) rejects
    hostnames in `remote` lines because DNS is blocked until the tunnel is up.
    """
    resolved: Dict[str, Optional[str]] = {}
    out = ["# " + GENERATED_BY,
           "# Source: openvpn/%s/%s with remote hostnames resolved (gluetun needs IP addresses)."
           % (vpn.name, vpn.ovpn.name)]
    for line in read_lines(vpn.ovpn):
        m = _REMOTE.match(line)
        if m and not line.strip().startswith(("#", ";")):
            host = m.group(2)
            try:
                ipaddress.ip_address(host)
            except ValueError:
                if host not in resolved:
                    resolved[host] = resolver(host)
                    if resolved[host] is None:
                        rep.warn("openvpn/%s: cannot resolve %s; gluetun will refuse this remote line"
                                 % (vpn.name, host))
                ip = resolved[host]
                if ip:
                    line = "%s%s%s" % (m.group(1), ip, m.group(3))
        out.append(line)
    return "\n".join(out) + "\n"


