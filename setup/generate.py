class Vpn:
    __slots__ = ("index", "dirname", "ovpn", "secret", "hostnames",
                 "remote_count")

    def __init__(self, index, dirname, ovpn, secret, hostnames, remote_count):
        self.index = index
        self.dirname = dirname
        self.ovpn = ovpn            # Path of the user's .ovpn
        self.secret = secret        # (user, password) or None
        self.hostnames = hostnames  # remote hosts that are not IP literals
        self.remote_count = remote_count

    @property
    def container(self):
        return VPN_CONTAINER.format(self.index)

    @property
    def service(self):
        return "vpn{}".format(self.index)

    @property
    def node_name(self):
        return "vpn-{}".format(self.index)

    @property
    def addr(self):
        return "{}:{}".format(self.container, GLUETUN_HTTP_PORT)

    @property
    def needs_resolved_copy(self):
        return bool(self.hostnames)


def _is_ip(text):
    try:
        ipaddress.ip_address(text)
    except ValueError:
        return False
    return True


def find_remotes(ovpn_text):
    """Return [(line_index, host)] for every active `remote` line."""
    remotes = []
    for index, line in enumerate(ovpn_text.splitlines()):
        match = _REMOTE_RE.match(line)
        if match:
            remotes.append((index, match.group(2)))
    return remotes


def parse_secret(path):
    lines = [line.strip() for line in
             path.read_text(encoding="utf-8", errors="replace").splitlines()]
    lines = [line for line in lines if line]
    if len(lines) < 2:
        raise InputError(
            "{}: expected the username on line 1 and the password on "
            "line 2".format(path))
    user, password = lines[0], lines[1]
    for value, what in ((user, "username"), (password, "password")):
        if "'" in value or "\\" in value:
            raise InputError(
                "{}: the {} contains ' or \\, which cannot be written safely "
                "to gluetun.env".format(path, what))
    return user, password


def discover_vpns(openvpn_dir, warn):
    if not openvpn_dir.is_dir():
        return []
    vpns = []
    for entry in sorted(openvpn_dir.iterdir(), key=lambda p: p.name):
        if not entry.is_dir() or entry.name.startswith("."):
            continue
        rel = "openvpn/{}".format(entry.name)
        if not _SAFE_NAME_RE.match(entry.name):
            raise InputError(
                "{}: directory names may only contain letters, digits, "
                "'.', '_' and '-'".format(rel))
        configs = sorted(p for p in entry.glob("*.ovpn") if p.is_file())
        if not configs:
            raise InputError("{}: no .ovpn file found".format(rel))
        if len(configs) > 1:
            warn("{}: several .ovpn files, using {}".format(rel, configs[0].name))
        ovpn = configs[0]
        if not _SAFE_NAME_RE.match(ovpn.name):
            raise InputError(
                "{}/{}: file names may only contain letters, digits, '.', '_' "
                "and '-'".format(rel, ovpn.name))
        remotes = find_remotes(ovpn.read_text(encoding="utf-8", errors="replace"))
        if not remotes:
            raise InputError(
                "{}/{}: no 'remote' line found (gluetun needs one)".format(
                    rel, ovpn.name))
        hostnames = sorted({host for _, host in remotes if not _is_ip(host)})
        secret_path = entry / "secret"
        secret = parse_secret(secret_path) if secret_path.is_file() else None
        if secret is None:
            warn("{}: no 'secret' file, gluetun will start without "
                 "OPENVPN_USER/OPENVPN_PASSWORD".format(rel))
        vpns.append(Vpn(len(vpns) + 1, entry.name, ovpn, secret, hostnames,
                        len(remotes)))
    return vpns


def default_resolver(host):
    """Resolve a hostname to a sorted list of IP addresses (IPv4 first)."""
    addresses = []
    for family in (socket.AF_INET, socket.AF_INET6):
        try:
            infos = socket.getaddrinfo(host, None, family, socket.SOCK_STREAM)
        except (socket.gaierror, UnicodeError):
            continue
        found = sorted({info[4][0] for info in infos},
                       key=lambda a: ipaddress.ip_address(a))
        addresses.extend(found)
        if addresses:
            break
    return addresses


def render_gluetun_conf(vpn, resolver):
    """Copy of the user's .ovpn with remote hostnames replaced by IPs."""
    text = vpn.ovpn.read_text(encoding="utf-8", errors="replace")
    lines = text.splitlines()
    resolved = {}
    failed = []
    for host in vpn.hostnames:
        addresses = resolver(host)
        if addresses:
            resolved[host] = addresses[0]
        else:
            failed.append(host)
    if failed:
        raise InputError(
            "openvpn/{}/{}: cannot resolve remote host(s) {}. gluetun's custom "
            "provider only accepts IP addresses: fix DNS, put an IP address in "
            "the remote line, or remove the directory.".format(
                vpn.dirname, vpn.ovpn.name, ", ".join(failed)))
    output = []
    for line in lines:
        match = _REMOTE_RE.match(line)
        if match and match.group(2) in resolved:
            output.append("# {}  (resolved by setup/generate.py)".format(
                line.strip()))
            line = "remote {}{}".format(resolved[match.group(2)],
                                        match.group(3))
        output.append(line)
    lines = output
    header = (
        "# Generated by setup/generate.py from {} - do not edit.\n"
        "# gluetun only accepts IP addresses in 'remote' lines, so hostnames\n"
        "# were resolved when the generator ran. Re-run it if the IP changes.\n"
    ).format(vpn.ovpn.name)
    return header + "\n".join(lines) + "\n"


def render_gluetun_env(vpn):
    user, password = vpn.secret
    return (
        "# Generated by setup/generate.py from openvpn/{}/secret.\n"
        "# Contains credentials: never commit this file.\n"
        "OPENVPN_USER='{}'\n"
        "OPENVPN_PASSWORD='{}'\n"
    ).format(vpn.dirname, user, password)


