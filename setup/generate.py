def write_file(path: Path, content: str, mode: int = 0o644) -> bool:
    """Atomically write `content`; returns False when the file was unchanged."""
    try:
        if path.read_text(encoding="utf-8") == content:
            if (path.stat().st_mode & 0o777) != mode:
                try:
                    os.chmod(path, mode)
                except PermissionError:
                    pass
            return False
    except (FileNotFoundError, UnicodeDecodeError):
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix="." + path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except FileNotFoundError:
            pass
        raise
    return True


def file_differs(path: Path, content: str) -> bool:
    try:
        return path.read_text(encoding="utf-8") != content
    except (FileNotFoundError, UnicodeDecodeError):
        return True


def generate(root: Path, squid_only: bool = False, rep: Optional[Reporter] = None,
             resolver: Resolver = default_resolver) -> int:
    rep = rep or Reporter()
    template_path = root / "template" / "squid.conf"
    if not template_path.is_file():
        rep.stream.write("error: %s not found\n" % template_path)
        return 1

    upstreams = parse_proxy_file(root / "proxyList.txt", rep)
    public = parse_proxy_file(root / "publicProxyList.txt", rep, public_only=True)
    upstreams, public = dedupe(upstreams, public, rep)
    vpns = discover_vpns(root / "openvpn", rep)

    if not upstreams and not public and not vpns:
        rep.stream.write(
            "error: no usable upstream found. Add lines like host:port[:scheme[:user:pass]] to "
            "proxyList.txt (or publicProxyList.txt), or an OpenVPN directory openvpn/<name>/ "
            "containing a .ovpn file.\n")
        rep.summary()
        return 2

    plan = build_plan(upstreams, public, vpns)
    template = template_path.read_text(encoding="utf-8")
    squid_conf = render_squid_conf(template, plan.squid_peers)
    gost_yaml = render_gost_yaml(plan)
    # In --squid-only mode the allowlist is only needed for the config hash.
    allow_rep = Reporter(stream=io.StringIO(), quiet=True) if squid_only else rep
    allowlist = "".join(a + "\n" for a in parse_allowlist(root / "template" / "allowed_ip.txt", allow_rep))
    hashes = {
        # publicProxyList.txt peers are excluded: the cron job applies them
        # with `squid -k reconfigure`, they must not force a recreate.
        "squid": config_hash(template, allowlist, *plan.squid_peers_fixed),
        "gost": config_hash(gost_yaml),
    }
    # The VPN label must follow the file that is actually mounted. For a .ovpn
    # with hostnames that is the derived gluetun.conf, whose resolved IPs can
    # change between runs while the source file stays the same.
    derived_confs: Dict[str, str] = {}
    for vpn in vpns:
        if vpn.needs_derived_config:
            if squid_only:
                # The cron path must not depend on DNS: hash what is mounted now.
                try:
                    mounted = (root / "openvpn" / vpn.name / "gluetun.conf").read_text(encoding="utf-8")
                except (FileNotFoundError, UnicodeDecodeError):
                    mounted = vpn.ovpn.read_text(encoding="utf-8", errors="replace")
            else:
                derived_confs[vpn.name] = render_gluetun_conf(vpn, resolver, rep)
                mounted = derived_confs[vpn.name]
        else:
            mounted = vpn.ovpn.read_text(encoding="utf-8", errors="replace")
        hashes[vpn.service] = config_hash(mounted)
    compose = render_compose(plan, hashes)

    config_dir = root / "config"
    if squid_only:
        changed = write_file(config_dir / "squid.conf", squid_conf)
        stale = [str(p.relative_to(root)) for p, c in ((config_dir / "gost.yaml", gost_yaml),
                                                       (root / "docker-compose.yml", compose)) if file_differs(p, c)]
        if stale:
            rep.warn("%s out of date (proxyList.txt, openvpn/ or the templates changed): run "
                     "`python3 setup/generate.py && docker compose up -d` to apply everything"
                     % " and ".join(stale))
        rep.info("config/squid.conf %s: %d cache_peer(s)" % ("written" if changed else "unchanged",
                                                              len(plan.squid_peers)))
        rep.summary()
        return 0

    outputs: List[Tuple[Path, str, int]] = [
        (config_dir / "squid.conf", squid_conf, 0o644),
        (config_dir / "allowed_ip.txt", allowlist, 0o644),
        (config_dir / "gost.yaml", gost_yaml, 0o600),
        (root / "docker-compose.yml", compose, 0o644),
    ]
    for vpn in vpns:
        vdir = root / "openvpn" / vpn.name
        if vpn.user is not None:
            outputs.append((vdir / "gluetun.env", render_gluetun_env(vpn), 0o600))
        if vpn.needs_derived_config:
            outputs.append((vdir / "gluetun.conf", derived_confs[vpn.name], 0o600))

    for path, content, mode in outputs:
        changed = write_file(path, content, mode)
        rep.info("%-40s %s" % (path.relative_to(root), "written" if changed else "unchanged"))

    c = plan.counts
    rep.info("squid: %d cache_peer(s): %d public, %d httpsquid, %d via gost, %d https, %d vpn"
             % (len(plan.squid_peers), c["public"], c["private"], c["gost"], c["https"], c["vpn"]))
    for sp in plan.static_ports:
        rep.info("static port %d -> %s" % (sp.port, sp.description))
    rep.info("next: docker compose up -d --remove-orphans")
    rep.summary()
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    default_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description="Generate Squid/gost/gluetun configuration and docker-compose.yml.")
    parser.add_argument("--root", type=Path, default=default_root,
                        help="repository root containing proxyList.txt (default: %(default)s)")
    parser.add_argument("--squid-only", action="store_true",
                        help="only rewrite config/squid.conf (used by public_proxy_cron.sh before "
                             "`squid -k reconfigure`)")
    parser.add_argument("-q", "--quiet", action="store_true", help="only print warnings and errors")
    args = parser.parse_args(argv)
    rep = Reporter(quiet=args.quiet)
    return generate(args.root.resolve(), squid_only=args.squid_only, rep=rep)


if __name__ == "__main__":
    sys.exit(main())
